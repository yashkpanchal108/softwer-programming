//Write a short comparison (3-4 lines each) of MySQL, PostgreSQL, Oracle, and SQLite, focusing on where each one is commonly used (for example: web apps, mobile apps, enterprise systems, etc.).

-- 1. MySQL

-- MySQL is a popular open-source relational database management system.
-- It is commonly used for web applications and websites.
-- It works well with technologies like PHP, Python, and Java.
-- It is widely used because it is easy to use and has good performance.

-- 2. PostgreSQL

-- PostgreSQL is an advanced open-source relational database system.
-- It is commonly used in web applications, data analysis, and complex systems.
-- It supports advanced features and complex queries.
-- It is suitable for applications that need high reliability and scalability.

-- 3. Oracle

-- Oracle Database is a powerful commercial relational database system.
-- It is mainly used in large enterprise systems, banking, and government organizations.
-- It provides strong security, reliability, and high performance.
-- It is suitable for handling large amounts of business data.

-- 4. SQLite

-- SQLite is a lightweight, serverless database system.
-- It is commonly used in mobile apps, desktop applications, and embedded systems.
-- It stores the complete database in a single file.
-- It is useful when a full database server is not required.